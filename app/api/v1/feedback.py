from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.feedback import PeerFeedbackCreate, PeerFeedbackUpdate, PeerFeedbackResponse
from app.services.feedback_service import PeerFeedbackService

router = APIRouter()

@router.post("/", response_model=PeerFeedbackResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: PeerFeedbackCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new PeerFeedback record.
    """
    return await PeerFeedbackService.create(db, obj_in)

@router.get("/", response_model=List[PeerFeedbackResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all PeerFeedback records.
    """
    return await PeerFeedbackService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=PeerFeedbackResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific PeerFeedback record by ID.
    """
    return await PeerFeedbackService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=PeerFeedbackResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: PeerFeedbackUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific PeerFeedback record.
    """
    return await PeerFeedbackService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=PeerFeedbackResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific PeerFeedback record. Only Admins can perform this action.
    """
    return await PeerFeedbackService.delete(db, record_id)

