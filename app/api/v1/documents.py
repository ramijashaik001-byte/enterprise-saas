from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.documents import DocumentCreate, DocumentUpdate, DocumentResponse
from app.services.documents_service import DocumentService

router = APIRouter()

@router.post("/", response_model=DocumentResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: DocumentCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new Document record.
    """
    return await DocumentService.create(db, obj_in)

@router.get("/", response_model=List[DocumentResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all Document records.
    """
    return await DocumentService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=DocumentResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific Document record by ID.
    """
    return await DocumentService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=DocumentResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: DocumentUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific Document record.
    """
    return await DocumentService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=DocumentResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific Document record. Only Admins can perform this action.
    """
    return await DocumentService.delete(db, record_id)

