from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.onboarding import OnboardingTaskCreate, OnboardingTaskUpdate, OnboardingTaskResponse
from app.services.onboarding_service import OnboardingTaskService

router = APIRouter()

@router.post("/", response_model=OnboardingTaskResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: OnboardingTaskCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new OnboardingTask record.
    """
    return await OnboardingTaskService.create(db, obj_in)

@router.get("/", response_model=List[OnboardingTaskResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all OnboardingTask records.
    """
    return await OnboardingTaskService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=OnboardingTaskResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific OnboardingTask record by ID.
    """
    return await OnboardingTaskService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=OnboardingTaskResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: OnboardingTaskUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific OnboardingTask record.
    """
    return await OnboardingTaskService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=OnboardingTaskResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific OnboardingTask record. Only Admins can perform this action.
    """
    return await OnboardingTaskService.delete(db, record_id)

