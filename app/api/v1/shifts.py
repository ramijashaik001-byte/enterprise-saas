from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.shifts import ShiftScheduleCreate, ShiftScheduleUpdate, ShiftScheduleResponse
from app.services.shifts_service import ShiftScheduleService

router = APIRouter()

@router.post("/", response_model=ShiftScheduleResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: ShiftScheduleCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new ShiftSchedule record.
    """
    return await ShiftScheduleService.create(db, obj_in)

@router.get("/", response_model=List[ShiftScheduleResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all ShiftSchedule records.
    """
    return await ShiftScheduleService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=ShiftScheduleResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific ShiftSchedule record by ID.
    """
    return await ShiftScheduleService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=ShiftScheduleResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: ShiftScheduleUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific ShiftSchedule record.
    """
    return await ShiftScheduleService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=ShiftScheduleResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific ShiftSchedule record. Only Admins can perform this action.
    """
    return await ShiftScheduleService.delete(db, record_id)

