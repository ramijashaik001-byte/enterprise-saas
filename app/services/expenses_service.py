from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.future import select
from typing import List, Optional
from app.models.expenses import ExpenseClaim
from app.schemas.expenses import ExpenseClaimCreate, ExpenseClaimUpdate
from app.core.tenancy import get_tenant_context
from fastapi import HTTPException, status
import logging

logger = logging.getLogger("saas.service.expenses")

class ExpenseClaimService:
    @staticmethod
    async def create(db: AsyncSession, obj_in: ExpenseClaimCreate) -> ExpenseClaim:
        tenant_id = get_tenant_context()
        logger.info(f"Creating expenses record for tenant: {tenant_id}")
        
        db_obj = ExpenseClaim(
            tenant_id=tenant_id,
            **obj_in.model_dump()
        )
        db.add(db_obj)
        await db.flush()
        return db_obj

    @staticmethod
    async def get_by_id(db: AsyncSession, obj_id: int) -> ExpenseClaim:
        tenant_id = get_tenant_context()
        query = select(ExpenseClaim).where(
            (ExpenseClaim.id == obj_id) & 
            (ExpenseClaim.tenant_id == tenant_id)
        )
        result = await db.execute(query)
        db_obj = result.scalar_one_or_none()
        if not db_obj:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"ExpenseClaim not found"
            )
        return db_obj

    @staticmethod
    async def get_all(db: AsyncSession, skip: int = 0, limit: int = 100) -> List[ExpenseClaim]:
        tenant_id = get_tenant_context()
        query = select(ExpenseClaim).where(ExpenseClaim.tenant_id == tenant_id).offset(skip).limit(limit)
        result = await db.execute(query)
        return list(result.scalars().all())

    @staticmethod
    async def update(db: AsyncSession, obj_id: int, obj_in: ExpenseClaimUpdate) -> ExpenseClaim:
        db_obj = await ExpenseClaimService.get_by_id(db, obj_id)
        update_data = obj_in.model_dump(exclude_unset=True)
        for field, value in update_data.items():
            setattr(db_obj, field, value)
        db.add(db_obj)
        await db.flush()
        return db_obj

    @staticmethod
    async def delete(db: AsyncSession, obj_id: int) -> ExpenseClaim:
        db_obj = await ExpenseClaimService.get_by_id(db, obj_id)
        await db.delete(db_obj)
        await db.flush()
        return db_obj

