from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.audit_logs import AuditLogCreate, AuditLogUpdate, AuditLogResponse
from app.services.audit_logs_service import AuditLogService

router = APIRouter()

@router.post("/", response_model=AuditLogResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: AuditLogCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new AuditLog record.
    """
    return await AuditLogService.create(db, obj_in)

@router.get("/", response_model=List[AuditLogResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all AuditLog records.
    """
    return await AuditLogService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=AuditLogResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific AuditLog record by ID.
    """
    return await AuditLogService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=AuditLogResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: AuditLogUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific AuditLog record.
    """
    return await AuditLogService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=AuditLogResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific AuditLog record. Only Admins can perform this action.
    """
    return await AuditLogService.delete(db, record_id)

