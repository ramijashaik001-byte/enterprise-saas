from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.attendance import AttendanceCreate, AttendanceUpdate, AttendanceResponse
from app.services.attendance_service import AttendanceService

router = APIRouter()

@router.post("/", response_model=AttendanceResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: AttendanceCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new Attendance record.
    """
    return await AttendanceService.create(db, obj_in)

@router.get("/", response_model=List[AttendanceResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all Attendance records.
    """
    return await AttendanceService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=AttendanceResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific Attendance record by ID.
    """
    return await AttendanceService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=AttendanceResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: AttendanceUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific Attendance record.
    """
    return await AttendanceService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=AttendanceResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific Attendance record. Only Admins can perform this action.
    """
    return await AttendanceService.delete(db, record_id)

