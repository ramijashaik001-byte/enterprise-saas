from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.projects import ProjectAllocationCreate, ProjectAllocationUpdate, ProjectAllocationResponse
from app.services.projects_service import ProjectAllocationService

router = APIRouter()

@router.post("/", response_model=ProjectAllocationResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: ProjectAllocationCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new ProjectAllocation record.
    """
    return await ProjectAllocationService.create(db, obj_in)

@router.get("/", response_model=List[ProjectAllocationResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all ProjectAllocation records.
    """
    return await ProjectAllocationService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=ProjectAllocationResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific ProjectAllocation record by ID.
    """
    return await ProjectAllocationService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=ProjectAllocationResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: ProjectAllocationUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific ProjectAllocation record.
    """
    return await ProjectAllocationService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=ProjectAllocationResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific ProjectAllocation record. Only Admins can perform this action.
    """
    return await ProjectAllocationService.delete(db, record_id)

