from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.compliance import ComplianceCheckCreate, ComplianceCheckUpdate, ComplianceCheckResponse
from app.services.compliance_service import ComplianceCheckService

router = APIRouter()

@router.post("/", response_model=ComplianceCheckResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: ComplianceCheckCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new ComplianceCheck record.
    """
    return await ComplianceCheckService.create(db, obj_in)

@router.get("/", response_model=List[ComplianceCheckResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all ComplianceCheck records.
    """
    return await ComplianceCheckService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=ComplianceCheckResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific ComplianceCheck record by ID.
    """
    return await ComplianceCheckService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=ComplianceCheckResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: ComplianceCheckUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific ComplianceCheck record.
    """
    return await ComplianceCheckService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=ComplianceCheckResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific ComplianceCheck record. Only Admins can perform this action.
    """
    return await ComplianceCheckService.delete(db, record_id)

