from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.workforce import WorkforceBudgetCreate, WorkforceBudgetUpdate, WorkforceBudgetResponse
from app.services.workforce_service import WorkforceBudgetService

router = APIRouter()

@router.post("/", response_model=WorkforceBudgetResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: WorkforceBudgetCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new WorkforceBudget record.
    """
    return await WorkforceBudgetService.create(db, obj_in)

@router.get("/", response_model=List[WorkforceBudgetResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all WorkforceBudget records.
    """
    return await WorkforceBudgetService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=WorkforceBudgetResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific WorkforceBudget record by ID.
    """
    return await WorkforceBudgetService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=WorkforceBudgetResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: WorkforceBudgetUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific WorkforceBudget record.
    """
    return await WorkforceBudgetService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=WorkforceBudgetResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific WorkforceBudget record. Only Admins can perform this action.
    """
    return await WorkforceBudgetService.delete(db, record_id)

