from typing import List
from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import check_role, get_current_user
from app.schemas.benefits import BenefitPlanCreate, BenefitPlanUpdate, BenefitPlanResponse
from app.services.benefits_service import BenefitPlanService

router = APIRouter()

@router.post("/", response_model=BenefitPlanResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def create_record(
    obj_in: BenefitPlanCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Create a new BenefitPlan record.
    """
    return await BenefitPlanService.create(db, obj_in)

@router.get("/", response_model=List[BenefitPlanResponse])
async def list_records(
    skip: int = 0,
    limit: int = 100,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get all BenefitPlan records.
    """
    return await BenefitPlanService.get_all(db, skip=skip, limit=limit)

@router.get("/{record_id}", response_model=BenefitPlanResponse)
async def get_record(
    record_id: int,
    current_user = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """
    Get specific BenefitPlan record by ID.
    """
    return await BenefitPlanService.get_by_id(db, record_id)

@router.put("/{record_id}", response_model=BenefitPlanResponse, dependencies=[Depends(check_role(["admin", "hr_manager"]))])
async def update_record(
    record_id: int,
    obj_in: BenefitPlanUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    Update specific BenefitPlan record.
    """
    return await BenefitPlanService.update(db, record_id, obj_in)

@router.delete("/{record_id}", response_model=BenefitPlanResponse, dependencies=[Depends(check_role(["admin"]))])
async def delete_record(
    record_id: int,
    db: AsyncSession = Depends(get_db)
):
    """
    Delete specific BenefitPlan record. Only Admins can perform this action.
    """
    return await BenefitPlanService.delete(db, record_id)

